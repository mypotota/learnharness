const box = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
const grow = ([x, y]) => {
  box.minX = Math.min(box.minX, x); box.maxX = Math.max(box.maxX, x);
  box.minY = Math.min(box.minY, y); box.maxY = Math.max(box.maxY, y);
};

function transformD(d, m) {
  const tokens = d.match(/[MLCZ]|-?\d*\.?\d+(?:e-?\d+)?/g);
  let out = "", i = 0;
  while (i < tokens.length) {
    const t = tokens[i++];
    if (t === "M" || t === "L") {
      const p = apply(m, +tokens[i++], +tokens[i++]);
      grow(p);
      out += `${t}${p[0].toFixed(2)},${p[1].toFixed(2)}`;
    } else if (t === "C") {
      const p = [];
      for (let k = 0; k < 3; k++) {
        const q = apply(m, +tokens[i++], +tokens[i++]);
        grow(q); p.push(q);
      }
      out += `C${p.map(([a, b]) => `${a.toFixed(2)},${b.toFixed(2)}`).join(" ")}`;
    } else if (t === "Z") {
      out += "Z";
    } else {
      throw new Error("unexpected token " + t);
    }
  }
  return out;
}

const circleM = total([1.261034, 0, -0, 1.261034, 3139.627182, -45.007413]);
const [ccx, ccy] = apply(circleM, 1270.5, 3988.5);
const cr = 683.5 * Math.sqrt(Math.abs(circleM[0] * circleM[3] - circleM[1] * circleM[2]));
grow([ccx - cr, ccy - cr]);
grow([ccx + cr, ccy + cr]);

const raw = paths.map((p) => ({ fill: p.fill, d: transformD(p.d, p.m) }));

const w = box.maxX - box.minX, h = box.maxY - box.minY;
// The system splash scales this like an adaptive icon: content must sit inside
// the central 2/3 (Android's 72/108 safe zone) or it looks oversized/clipped.
const pad = w / 4;
const shiftD = (d) => d.replace(/(-?\d*\.?\d+),(-?\d*\.?\d+)/g, (_, a, b) =>
  `${(+a - box.minX + pad).toFixed(2)},${(+b - box.minY + pad).toFixed(2)}`);

const items = raw.map((p) => ({ fill: p.fill, d: shiftD(p.d) }));
const scx = ccx - box.minX + pad, scy = ccy - box.minY + pad, r = cr.toFixed(2);
items.push({
  fill: "@color/splash_mark",
  d: `M${(scx - cr).toFixed(2)},${scy.toFixed(2)}a${r},${r} 0 1,0 ${(cr * 2).toFixed(2)},0a${r},${r} 0 1,0 ${(-cr * 2).toFixed(2)},0Z`,
});

const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/scripts/generate-splash-mark.mjs from
     components/lh-mark.tsx: the launch mark and the Android 12+ system
     splash icon are the app's real mark, not a redrawn copy. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="${(w + pad * 2).toFixed(2)}"
    android:viewportHeight="${(h + pad * 2).toFixed(2)}">
${items.map((item) => `    <path
        android:fillColor="${item.fill}"
        android:fillType="evenOdd"
        android:pathData="${item.d}" />`).join("\n")}
</vector>
`;

const target = fileURLToPath(new URL("../android/app/src/main/res/drawable/ic_splash_mark.xml", import.meta.url));
fs.writeFileSync(target, xml);
